export function translate(text,vars={},language='ar') {
 const source=String(text??'');
 const template=language==='en'&&Object.hasOwn(english,source)?english[source]:source;
 const values=vars&&typeof vars==='object'?vars:{};
 return template.replace(/\{([A-Za-z_][A-Za-z0-9_]*)\}/g,(placeholder,key)=>
  Object.hasOwn(values,key)&&values[key]!==undefined&&values[key]!==null?String(values[key]):placeholder);
}

export function createTranslator(getLanguage=()=> 'ar') {
 if(typeof getLanguage!=='function')throw new TypeError('A language provider function is required');
 return (text,vars={},language=getLanguage())=>translate(text,vars,language);
}
